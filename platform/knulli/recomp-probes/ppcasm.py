"""Minimal PowerPC (Broadway subset) assembler for Nebula translator probes. Big-endian output."""
import struct
def D(op,rt,ra,imm): return (op<<26)|(rt<<21)|(ra<<16)|(imm&0xFFFF)
def X(op,rt,ra,rb,xo,rc=0): return (op<<26)|(rt<<21)|(ra<<16)|(rb<<11)|(xo<<1)|rc
def XO(rt,ra,rb,xo,oe=0,rc=0): return (31<<26)|(rt<<21)|(ra<<16)|(rb<<11)|(oe<<10)|(xo<<1)|rc
def A(op,frt,fra,frb,frc,xo,rc=0): return (op<<26)|(frt<<21)|(fra<<16)|(frb<<11)|(frc<<6)|(xo<<1)|rc
class Asm:
    def __init__(s,base): s.base=base; s.w=[]; s.labels={}; s.fix=[]
    def pc(s): return s.base+4*len(s.w)
    def L(s,n): s.labels[n]=s.pc()
    def e(s,x): s.w.append(x & 0xFFFFFFFF)
    li=lambda s,rt,v: s.e(D(14,rt,0,v))
    addi=lambda s,rt,ra,v: s.e(D(14,rt,ra,v))
    lis=lambda s,rt,v: s.e(D(15,rt,0,v))
    ori=lambda s,ra,rs,v: s.e(D(24,rs,ra,v))
    lwz=lambda s,rt,d,ra: s.e(D(32,rt,ra,d))
    lwzu=lambda s,rt,d,ra: s.e(D(33,rt,ra,d))
    stw=lambda s,rt,d,ra: s.e(D(36,rt,ra,d))
    stwu=lambda s,rt,d,ra: s.e(D(37,rt,ra,d))
    lfs=lambda s,ft,d,ra: s.e(D(48,ft,ra,d))
    lfsu=lambda s,ft,d,ra: s.e(D(49,ft,ra,d))
    stfs=lambda s,ft,d,ra: s.e(D(52,ft,ra,d))
    add=lambda s,rt,ra,rb: s.e(XO(rt,ra,rb,266))
    subf=lambda s,rt,ra,rb: s.e(XO(rt,ra,rb,40))
    mullw=lambda s,rt,ra,rb: s.e(XO(rt,ra,rb,235))
    divw=lambda s,rt,ra,rb: s.e(XO(rt,ra,rb,491))
    divwu=lambda s,rt,ra,rb: s.e(XO(rt,ra,rb,459))
    xor=lambda s,ra,rs,rb: s.e(X(31,rs,ra,rb,316))
    def rlwinm(s,ra,rs,sh,mb,me): s.e((21<<26)|(rs<<21)|(ra<<16)|(sh<<11)|(mb<<6)|(me<<1))
    def slwi(s,ra,rs,n): s.rlwinm(ra,rs,n,0,31-n)
    def srwi(s,ra,rs,n): s.rlwinm(ra,rs,32-n,n,31)
    cmpwi=lambda s,ra,v: s.e(D(11,0,ra,v))
    cmplw=lambda s,ra,rb: s.e(X(31,0,ra,rb,32))
    mtctr=lambda s,rs: s.e((31<<26)|(rs<<21)|(9<<16)|(0<<11)|(467<<1))
    mflr=lambda s,rt: s.e((31<<26)|(rt<<21)|(8<<16)|(339<<1))
    mtlr=lambda s,rs: s.e((31<<26)|(rs<<21)|(8<<16)|(467<<1))
    fadds=lambda s,t,a,b: s.e(A(59,t,a,b,0,21))
    fmuls=lambda s,t,a,c: s.e(A(59,t,a,0,c,25))
    fmadds=lambda s,t,a,c,b: s.e(A(59,t,a,b,c,29))
    fsubs=lambda s,t,a,b: s.e(A(59,t,a,b,0,20))
    fmr=lambda s,t,b: s.e(X(63,t,0,b,72))
    ps_madd=lambda s,t,a,c,b: s.e(A(4,t,a,b,c,29))
    ps_add=lambda s,t,a,b: s.e(A(4,t,a,b,0,21))
    ps_mul=lambda s,t,a,c: s.e(A(4,t,a,0,c,25))
    ps_sub=lambda s,t,a,b: s.e(A(4,t,a,b,0,20))
    lfd=lambda s,ft,d,ra: s.e(D(50,ft,ra,d))
    fctiwz=lambda s,t,b: s.e(X(63,t,0,b,15))
    stfiwx=lambda s,fs,ra,rb: s.e(X(31,fs,ra,rb,983))
    stfd=lambda s,fs,d,ra: s.e(D(54,fs,ra,d))
    blr=lambda s: s.e(0x4E800020)
    def _br(s,kind,label,bo=0,bi=0): s.fix.append((len(s.w),kind,label,bo,bi)); s.e(0)
    b=lambda s,l: s._br('b',l)
    bl=lambda s,l: s._br('bl',l)
    bdnz=lambda s,l: s._br('bc',l,16,0)
    bne=lambda s,l: s._br('bc',l,4,2)
    beq=lambda s,l: s._br('bc',l,12,2)
    blt=lambda s,l: s._br('bc',l,12,0)
    def bytes(s):
        for i,k,l,bo,bi in s.fix:
            off=s.labels[l]-(s.base+4*i)
            if k in('b','bl'): s.w[i]=(18<<26)|(off&0x3FFFFFC)|(1 if k=='bl' else 0)
            else: s.w[i]=(16<<26)|(bo<<21)|(bi<<16)|(off&0xFFFC)
        return b''.join(struct.pack('>I',x) for x in s.w)
